#!/usr/bin/env node
// Parse the three historical fortune files into js/fortunes.js.
// The browser cannot fetch plain files from file://, so the game ships
// pre-generated data and stays 100% offline.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = [
  ['informatique', 'informatique'],
  ['multidesk', 'multidesk'],
  ['tribune-linuxfr', 'tribune-linuxfr'],
];

const clean = (value) => value.replace(/\s+/g, ' ').trim();

function splitBlocks(raw) {
  return raw
    .replace(/\r\n?/g, '\n')
    .split(/^\s*%\s*$/m)
    .map((block) => block.trim())
    .filter(Boolean);
}

function extractAuthor(source, block) {
  if (source === 'multidesk') {
    const m = block.match(/\n[ \t]*--[ \t]*([\s\S]*?)[ \t]*--[ \t]*$/);
    if (m) {
      return { author: clean(m[1]), text: block.slice(0, m.index).trim() };
    }
  }
  if (source === 'informatique') {
    const m = block.match(/\n[ \t]*-?-?\+-+([\s\S]*?)-\+-[ \t]*$/);
    if (m) {
      return { author: clean(m[1]), text: block.slice(0, m.index).trim() };
    }
  }
  return { author: '', text: block };
}

const entries = [];
for (const [source, file] of sources) {
  const raw = readFileSync(join(root, file), 'utf8');
  const seen = new Set();
  let index = 0;
  for (const block of splitBlocks(raw)) {
    const { author, text } = extractAuthor(source, block);
    const normalized = clean(text);
    if (!normalized || seen.has(normalized)) continue;
    seen.add(normalized);
    entries.push({
      id: `${source}:${index}`,
      s: source,
      t: normalized,
      a: author,
    });
    index += 1;
  }
}

const payload = `/* Generated by scripts/build-fortunes.mjs from the three lore files.
   Do not edit by hand: run \`node scripts/build-fortunes.mjs\`. */
window.FORTUNES = ${JSON.stringify(entries, null, 1)};
`;

writeFileSync(join(root, 'js', 'fortunes.js'), payload);

const counts = entries.reduce((acc, entry) => {
  acc[entry.s] = (acc[entry.s] || 0) + 1;
  return acc;
}, {});
console.log(`fortunes: ${entries.length}`, counts);
